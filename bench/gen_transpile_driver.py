#!/usr/bin/env python3
"""Generate a differential driver for the *transpile* pipeline.

difftest.sh exercises only `--mode emit` (decompilation, Pipeline A), where
arguments arrive as sign-extended uint64 parameters. The real product is the
transpiler (Pipeline B), where arguments are zero-extended uint32 memory loads
on the shared stack — different operand semantics that hid e.g. the width-aware
sign-flag bug. This driver calls every corpus function over a boundary-inclusive
grid and folds the results into one checksum, so transpiling the whole program
and comparing to the native run proves Pipeline-B equivalence at full width.
"""
import re
import sys

CORPUS = sys.argv[1] if len(sys.argv) > 1 else "bench/corpus.c"
src = open(CORPUS).read()

# name -> mode from difftest.sh's FUNCS list (i=int args, p=(int*,n,x),
# s=(char*), q=(int*,int*,n)). Only these are differentially tested.
FUNCS = ("add1:i addsub:i mulshift:i maxi:i mini:i absdiff:i sign:i clampu:i mix:i sumto:i countbits:i "
         "arraysum:p arraymax:p third:p counteq:p strlen_c:s udiv:i umod:i sdiv:i smod:i widemul:i "
         "hibyte:i hibyte3:i sxbyte:i sxword:i idxw:p spill2:i spill3:i "
         "sortpair:i poly:i stackarr:i fieldsum:p nestcond:i sumrec:i borrow:i cmp3:i favg:i fpoly:i fcmp:i fmix:i "
         "div64:i idiv64:i bswapi:i clz:i ctz:i widen:p interleave:q tlen:s stkarr:i x87arith:i x87cmp:i x87div:i "
         "rotl:i rotr:i imulh:i xchg3:i vshuf:i repset:i psA:i psB:i psC:i psD:i adc128:i atomadd:i atomcas:i "
         "atomxchg:i dshiftv:i")
mode = {f.split(":")[0]: f.split(":")[1] for f in FUNCS.split()}

# Parse each function's parameter types from its definition.
sig_re = re.compile(r'^\s*((?:unsigned\s+long\s+long|long\s+long|unsigned|int|long|short|void)[\w\s\*]*?)\s+'
                    r'(\w+)\s*\(([^)]*)\)\s*\{', re.M)
# Function bodies (name -> source span) so we can skip ones the 32-bit target
# can't build (`__int128` is unsupported by i686 mingw).
bodies = {}
defs = list(sig_re.finditer(src))
for i, m in enumerate(defs):
    end = defs[i + 1].start() if i + 1 < len(defs) else len(src)
    bodies[m.group(2)] = src[m.start():end]

# Features the i686 mingw target can't build from source (the corpus uses them
# for the decompiler path, which never recompiles the source as 32-bit).
UNSUPPORTED = ("__int128", "__v4", "__v2", "__vector", "__builtin_ia32", "__builtin_shuffle", "_mm_")


def unbuildable(name):
    body = bodies.get(name, "")
    return any(tok in body for tok in UNSUPPORTED)


sigs = {}
for ret, name, params in sig_re.findall(src):
    if name in mode and not unbuildable(name):
        ps = [p.strip() for p in params.split(",")] if params.strip() and params.strip() != "void" else []
        sigs[name] = (ret.strip(), ps)


def is64(ty):
    return "long long" in ty


def arg_expr(ty, slot, fmode):
    """A C expression feeding parameter `ty` from grid index `slot`. For pointer-
    mode functions the int args are counts/indices into an 8-element buffer, so
    clamp them to 0..7 to stay in bounds."""
    if "*" in ty:
        if "char" in ty:
            return "str"
        if "short" in ty:
            return "(const short*)buf"
        return "buf"  # const int*
    if is64(ty):
        return f"V64[(k+{slot})%n64]"
    if fmode in ("p", "q", "s"):
        return f"(V[(k+{slot})%n] & 7)"
    base = f"V[(k+{slot})%n]"
    if "unsigned" in ty:
        return f"(unsigned){base}"
    if "short" in ty:
        return f"(short){base}"
    return base


# Functions that loop/recurse on their (first) argument: an INT_MAX-class value
# would hang or blow the stack, so feed them a small count. The sign-boundary
# grid still covers every other function.
COUNT_DRIVEN = {"sumto": 0, "sumrec": 0}

lines = []
for name, (ret, ps) in sigs.items():
    clamp_slot = COUNT_DRIVEN.get(name)
    parts = []
    for i, p in enumerate(ps):
        e = arg_expr(p, i, mode[name])
        if i == clamp_slot and "*" not in p:
            e = f"(V[(k+{i})%n] & 63)"
        parts.append(e)
    args = ", ".join(parts)
    call = f"{name}({args})"
    if is64(ret):
        lines.append(f"    fold((uint64_t){call});")
    else:
        lines.append(f"    fold((uint64_t)(uint32_t)({call}));")

# Inline the corpus with target-unbuildable functions stripped, so the whole
# driver builds on the i686 target.
strip_spans = sorted((bodies[n] for n in bodies if unbuildable(n)), key=len, reverse=True)
corpus_src = src
for span in strip_spans:
    corpus_src = corpus_src.replace(span, "")

driver = f"""/* GENERATED by bench/gen_transpile_driver.py — do not edit. */
#include <stdio.h>
#include <stdint.h>
/* ---- corpus.c (inlined, __int128 functions stripped for 32-bit target) ---- */
{corpus_src}
/* ---- end corpus ---- */
static uint64_t H = 1469598103934665603ULL;
static void fold(uint64_t v){{ H ^= v; H *= 1099511628211ULL; H ^= H >> 29; }}
int main(void){{
  /* Values kept inside the corpus's overflow-safe range (like difftest) so the
     source has no signed-overflow UB and the native run is a stable ground truth.
     Crucially it includes NEGATIVES and bit patterns: that is enough to exercise
     the transpile pipeline's memory-operand sign handling (the bug class the
     decompile-only difftest cannot reach) — no INT_MIN arithmetic needed. */
  static const int V[] = {{ -16, -7, -3, -1, 0, 1, 2, 3, 7, 15, 16, 42, 47, -42, 31, -31 }};
  static const long long V64[] = {{ 0, 1, -1, 2, -2, 7, -7, 16, -16, 1000, -1000 }};
  const int n = sizeof(V)/sizeof(V[0]);
  const int n64 = sizeof(V64)/sizeof(V64[0]);
  int buf[8] = {{ 5, -3, 0, 2147483647, -2147483647-1, 7, -1, 3 }};
  char str[] = "hello world";
  for (int k = 0; k < n*n64; k++) {{
{chr(10).join(lines)}
  }}
  printf("H=%016llx\\n", (unsigned long long)H);
  return 0;
}}
"""
sys.stdout.write(driver)
sys.stderr.write(f"generated driver: {len(sigs)} functions\n")
